async function getOrCreateMedia(payload: Payload, filename: string) {
  const existing = await payload.find({
    collection: 'media',
    depth: 0,
    limit: 1,
    where: { filename: { equals: filename } },
  })

  if (existing.docs[0]) return existing.docs[0]

  const filePath = path.resolve(process.cwd(), 'src/assets', filename)
  const data = await fs.readFile(filePath)

  return payload.create({
    collection: 'media',
    data: {
      alt: path.basename(filename, path.extname(filename)),
      cropToSquare: false,
    },
    file: {
      data,
      mimetype: 'image/jpeg',
      name: filename,
      size: data.byteLength,
    },
  })
}

async function getOrCreateAuthor(payload: Payload) {
  const existing = await payload.find({
    collection: 'article-authors',
    depth: 0,
    limit: 1,
    where: { name: { equals: authorName } },
  })

  if (existing.docs[0]) return existing.docs[0]

  const fallbackAuthor = await payload.find({
    collection: 'article-authors',
    depth: 0,
    limit: 1,
  })
  const avatar = fallbackAuthor.docs[0]?.avatar

  if (typeof avatar !== 'number') {
    throw new Error('Cannot create the migrated author without an existing author avatar')
  }

  return payload.create({
    collection: 'article-authors',
    data: {
      name: authorName,
      avatar,
      role: 'Editor',
    },
  })
}

async function main() {
  const payload = await getPayloadClient()
  const editorConfig = await editorConfigFactory.default({ config: payload.config })
  const author = await getOrCreateAuthor(payload)
  let created = 0

  for (const article of articles) {
    const duplicate = await payload.find({
      collection: 'articles',
      depth: 0,
      limit: 1,
      where: {
        or: [{ slug: { equals: article.slug } }, { title: { equals: article.title } }],
      },
    })

    if (duplicate.docs[0]) {
      console.log(`Skipped existing article: ${article.title}`)
      continue
    }

    const coverImage = await getOrCreateMedia(payload, article.coverImage)
    const content = convertMarkdownToLexical({
      markdown: article.markdown,
      editorConfig,
    })

    await payload.create({
      collection: 'articles',
      data: {
        title: article.title,
        slug: article.slug,
        content,
        contentSummary: article.excerpt,
        coverImage: coverImage.id,
        author: author.id,
        category: article.category,
        status: statusOptions.published,
        publishedAt: article.publishedAt,
      },
    })
    created += 1
    console.log(`Created article: ${article.title}`)
  }

  console.log(`Migration complete: ${created} article(s) created`)
  process.exit(0)
}

void main().catch((error) => {
  console.error(error)
  process.exit(1)
})
